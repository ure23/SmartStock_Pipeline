"""Map workbook price-list rows to canonical product/material records."""

from __future__ import annotations

import sys

import psycopg

from smartstock_pipeline.db import (
    DatabaseConfig,
    DatabaseConfigurationError,
    DatabaseConnectionError,
    connect,
)


class WorkbookMappingError(RuntimeError):
    """Raised when source rows cannot be mapped without losing information."""


CREATE_PRODUCT_MAP = """
CREATE TABLE IF NOT EXISTS workbook_import.product_id_map (
    product_key TEXT PRIMARY KEY,
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    source_file_sha256 CHAR(64) NOT NULL,
    source_file_name TEXT NOT NULL,
    source_row_number INTEGER NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_file_name, source_row_number)
)
"""

REQUIRED_PRICE_LIST_COLUMNS = {
    "product",
    "unit_price",
    "source_file_sha256",
    "source_file_name",
    "source_row_number",
}


def import_workbook_products(config: DatabaseConfig | None = None) -> int:
    """Idempotently map the staged price list into ``public.products_materials``.

    Product IDs are generated once and persisted by normalized product name.
    Fields absent from the workbook (category, reorder level, status, and
    updated_at) remain NULL; the source is never modified.
    """
    with connect(config) as connection:
        column_rows = connection.execute(
            """SELECT column_name
               FROM information_schema.columns
               WHERE table_schema = 'workbook_import'
                 AND table_name = 'price_list'"""
        ).fetchall()
        available = {row[0] for row in column_rows}
        missing = sorted(REQUIRED_PRICE_LIST_COLUMNS - available)
        if missing:
            raise WorkbookMappingError(
                "workbook_import.price_list is missing required column(s): "
                + ", ".join(missing)
            )

        invalid_count = connection.execute(
            """SELECT COUNT(*)
               FROM workbook_import.price_list
               WHERE product IS NULL OR trim(product) = '' OR length(product) > 150
                  OR unit_price IS NULL OR unit_price < 0
                  OR unit_price >= 10000000000 OR scale(unit_price) > 2"""
        ).fetchone()[0]
        if invalid_count:
            raise WorkbookMappingError(
                f"Price list has {invalid_count} row(s) outside the canonical product contract"
            )

        ambiguous_count = connection.execute(
            """SELECT COUNT(*) FROM (
                   SELECT lower(trim(product))
                   FROM workbook_import.price_list
                   GROUP BY lower(trim(product))
                   HAVING COUNT(*) > 1
               ) AS duplicate_keys"""
        ).fetchone()[0]
        if ambiguous_count:
            raise WorkbookMappingError(
                f"Price list contains {ambiguous_count} ambiguous normalized product key(s)"
            )

        connection.execute(CREATE_PRODUCT_MAP)
        unmapped_canonical_count = connection.execute(
            """SELECT COUNT(*)
               FROM public.products_materials AS canonical
               LEFT JOIN workbook_import.product_id_map AS mapping
                 ON mapping.product_id = canonical.product_id
               WHERE mapping.product_id IS NULL"""
        ).fetchone()[0]
        if unmapped_canonical_count:
            raise WorkbookMappingError(
                f"Canonical products contains {unmapped_canonical_count} row(s) not owned by this workbook mapping"
            )
        connection.execute(
            """INSERT INTO workbook_import.product_id_map
                   (product_key, source_file_sha256, source_file_name, source_row_number)
               SELECT lower(trim(product)), source_file_sha256, source_file_name, source_row_number
               FROM workbook_import.price_list
               ON CONFLICT (product_key) DO UPDATE SET
                   source_file_sha256 = EXCLUDED.source_file_sha256,
                   source_file_name = EXCLUDED.source_file_name,
                   source_row_number = EXCLUDED.source_row_number,
                   last_seen_at = CURRENT_TIMESTAMP"""
        )
        connection.execute(
            """INSERT INTO public.products_materials
                   (product_id, product_name, category, unit_price, reorder_level, status, updated_at)
               SELECT map.product_id, price.product, NULL, price.unit_price,
                      NULL, NULL, NULL
               FROM workbook_import.price_list AS price
               JOIN workbook_import.product_id_map AS map
                 ON map.product_key = lower(trim(price.product))
               ON CONFLICT (product_id) DO UPDATE SET
                   product_name = EXCLUDED.product_name,
                   category = EXCLUDED.category,
                   unit_price = EXCLUDED.unit_price,
                   reorder_level = EXCLUDED.reorder_level,
                   status = EXCLUDED.status,
                   updated_at = EXCLUDED.updated_at"""
        )
        row_count = connection.execute(
            """SELECT COUNT(*)
               FROM workbook_import.price_list AS price
               JOIN workbook_import.product_id_map AS map
                 ON map.product_key = lower(trim(price.product))"""
        ).fetchone()[0]

        return row_count


def main() -> int:
    try:
        count = import_workbook_products()
    except (DatabaseConfigurationError, DatabaseConnectionError, WorkbookMappingError) as exc:
        print(f"Workbook product mapping failed: {exc}", file=sys.stderr)
        return 1
    except psycopg.Error:
        print("Workbook product mapping failed due to a database error", file=sys.stderr)
        return 1
    print(f"Mapped {count} price-list product row(s) into the canonical product table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
