"""Map staged workbook orders and lines into canonical records."""

from __future__ import annotations

import sys
from dataclasses import dataclass

import psycopg

from smartstock_pipeline.db import (
    DatabaseConfigurationError,
    DatabaseConnectionError,
    DatabaseConfig,
    connect,
)
from smartstock_pipeline.import_workbook_products import WorkbookMappingError


CREATE_ORDER_MAPS = """
CREATE TABLE IF NOT EXISTS workbook_import.customer_id_map (
    customer_key TEXT PRIMARY KEY,
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS workbook_import.order_id_map (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    sales_order_no TEXT NOT NULL,
    order_date DATE NOT NULL,
    order_time TIME NOT NULL,
    customer_key TEXT NOT NULL REFERENCES workbook_import.customer_id_map (customer_key),
    source_file_name TEXT NOT NULL,
    source_row_number INTEGER NOT NULL,
    source_file_sha256 CHAR(64) NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (sales_order_no, order_date, order_time, customer_key),
    UNIQUE (source_file_name, source_row_number)
);

CREATE TABLE IF NOT EXISTS workbook_import.order_item_id_map (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    source_file_name TEXT NOT NULL,
    source_row_number INTEGER NOT NULL,
    source_file_sha256 CHAR(64) NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (source_file_name, source_row_number),
    UNIQUE (source_file_sha256, source_row_number)
);

CREATE TABLE IF NOT EXISTS workbook_import.pipeline_quarantine (
    source_table TEXT NOT NULL,
    source_file_sha256 CHAR(64) NOT NULL,
    source_file_name TEXT NOT NULL,
    source_row_number INTEGER NOT NULL,
    reason_code TEXT NOT NULL,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (source_table, source_file_sha256, source_row_number, reason_code)
)
"""

TRACKER_COLUMNS = {
    "sales_order_no",
    "order_date",
    "order_time",
    "customer",
    "amount",
    "status",
    "source_file_sha256",
    "source_file_name",
    "source_row_number",
}
ITEM_COLUMNS = {
    "sales_order_no",
    "order_date",
    "order_time",
    "customer",
    "product",
    "quantity",
    "unit_price",
    "source_file_sha256",
    "source_file_name",
    "source_row_number",
}


@dataclass(frozen=True)
class WorkbookOrderImportResult:
    orders: int
    order_items: int
    quarantined_order_items: int


def _require_columns(connection, table_name: str, required: set[str]) -> None:
    rows = connection.execute(
        """SELECT column_name
           FROM information_schema.columns
           WHERE table_schema = 'workbook_import' AND table_name = %s""",
        (table_name,),
    ).fetchall()
    missing = sorted(required - {row[0] for row in rows})
    if missing:
        raise WorkbookMappingError(
            f"workbook_import.{table_name} is missing required column(s): "
            + ", ".join(missing)
        )


def import_workbook_orders_and_items(
    config: DatabaseConfig | None = None,
) -> WorkbookOrderImportResult:
    """Idempotently map orders and matched lines, quarantining unmatched rows.

    Generated integer IDs are stable through persisted mapping tables. The
    natural order key is sales_order_no + date + time + normalized customer;
    the source has no official numeric order/customer/product identifiers.
    Unmatched rows are recorded by source locator only, never copied into logs.
    """
    with connect(config) as connection:
        _require_columns(connection, "sales_order_tracker", TRACKER_COLUMNS)
        _require_columns(connection, "items_sold_tracker", ITEM_COLUMNS)
        product_map_exists = connection.execute(
            """SELECT to_regclass('workbook_import.product_id_map') IS NOT NULL"""
        ).fetchone()[0]
        if not product_map_exists:
            raise WorkbookMappingError(
                "Run product mapping before importing order items"
            )

        invalid_trackers = connection.execute(
            """SELECT COUNT(*) FROM workbook_import.sales_order_tracker
               WHERE sales_order_no IS NULL OR trim(sales_order_no) = ''
                  OR order_date IS NULL OR order_time IS NULL
                  OR customer IS NULL OR trim(customer) = ''
                  OR amount IS NULL OR amount < 0"""
        ).fetchone()[0]
        if invalid_trackers:
            raise WorkbookMappingError(
                f"Sales-order tracker has {invalid_trackers} row(s) missing required mapping fields"
            )

        duplicate_orders = connection.execute(
            """SELECT COUNT(*) FROM (
                   SELECT sales_order_no, order_date, order_time, lower(trim(customer))
                   FROM workbook_import.sales_order_tracker
                   GROUP BY sales_order_no, order_date, order_time, lower(trim(customer))
                   HAVING COUNT(*) > 1
               ) AS duplicate_keys"""
        ).fetchone()[0]
        if duplicate_orders:
            raise WorkbookMappingError(
                f"Sales-order tracker has {duplicate_orders} ambiguous natural order key(s)"
            )

        invalid_items = connection.execute(
            """SELECT COUNT(*) FROM workbook_import.items_sold_tracker
               WHERE sales_order_no IS NULL OR trim(sales_order_no) = ''
                  OR order_date IS NULL OR order_time IS NULL
                  OR customer IS NULL OR trim(customer) = ''
                  OR product IS NULL OR trim(product) = ''
                  OR quantity IS NULL OR quantity <= 0
                  OR unit_price IS NULL OR unit_price < 0
                  OR unit_price >= 10000000000 OR scale(unit_price) > 2"""
        ).fetchone()[0]
        if invalid_items:
            raise WorkbookMappingError(
                f"Item tracker has {invalid_items} row(s) outside the canonical line contract"
            )

        duplicate_item_locators = connection.execute(
            """SELECT COUNT(*) FROM (
                   SELECT source_file_name, source_row_number
                   FROM workbook_import.items_sold_tracker
                   GROUP BY source_file_name, source_row_number
                   HAVING COUNT(*) > 1
               ) AS duplicate_locators"""
        ).fetchone()[0]
        if duplicate_item_locators:
            raise WorkbookMappingError(
                f"Item tracker has {duplicate_item_locators} ambiguous source row locator(s)"
            )

        connection.execute("ALTER TABLE public.orders ALTER COLUMN total_amount TYPE NUMERIC")
        connection.execute("ALTER TABLE public.order_items ALTER COLUMN quantity TYPE NUMERIC")
        for statement in CREATE_ORDER_MAPS.split(";"):
            if statement.strip():
                connection.execute(statement)
        unmapped_order_count = connection.execute(
            """SELECT COUNT(*)
               FROM public.orders AS canonical
               LEFT JOIN workbook_import.order_id_map AS mapping
                 ON mapping.order_id = canonical.order_id
               WHERE mapping.order_id IS NULL"""
        ).fetchone()[0]
        unmapped_item_count = connection.execute(
            """SELECT COUNT(*)
               FROM public.order_items AS canonical
               LEFT JOIN workbook_import.order_item_id_map AS mapping
                 ON mapping.order_item_id = canonical.order_item_id
               WHERE mapping.order_item_id IS NULL"""
        ).fetchone()[0]
        if unmapped_order_count or unmapped_item_count:
            raise WorkbookMappingError(
                "Canonical order tables contain rows outside the workbook mappings "
                f"(orders={unmapped_order_count}, order_items={unmapped_item_count})"
            )
        connection.execute(
            """INSERT INTO workbook_import.customer_id_map (customer_key)
               SELECT DISTINCT lower(trim(customer))
               FROM workbook_import.sales_order_tracker
               ON CONFLICT (customer_key) DO UPDATE SET
                   last_seen_at = CURRENT_TIMESTAMP"""
        )
        connection.execute(
            """INSERT INTO workbook_import.order_id_map
                   (sales_order_no, order_date, order_time, customer_key,
                    source_file_name, source_row_number, source_file_sha256)
               SELECT sales_order_no, order_date, order_time, lower(trim(customer)),
                      source_file_name, source_row_number, source_file_sha256
               FROM workbook_import.sales_order_tracker
               ON CONFLICT (sales_order_no, order_date, order_time, customer_key)
               DO UPDATE SET source_file_name = EXCLUDED.source_file_name,
                             source_row_number = EXCLUDED.source_row_number,
                             source_file_sha256 = EXCLUDED.source_file_sha256,
                             last_seen_at = CURRENT_TIMESTAMP"""
        )
        connection.execute(
            """INSERT INTO workbook_import.order_item_id_map
                   (source_file_name, source_row_number, source_file_sha256)
               SELECT source_file_name, source_row_number, source_file_sha256
               FROM workbook_import.items_sold_tracker
               ON CONFLICT (source_file_name, source_row_number)
               DO UPDATE SET source_file_sha256 = EXCLUDED.source_file_sha256,
                             last_seen_at = CURRENT_TIMESTAMP"""
        )
        connection.execute(
            """INSERT INTO public.orders
                   (order_id, customer_id, order_date, status, total_amount)
               SELECT order_map.order_id, customer_map.customer_id,
                      tracker.order_date, tracker.status, tracker.amount
               FROM workbook_import.sales_order_tracker AS tracker
               JOIN workbook_import.order_id_map AS order_map
                 ON order_map.sales_order_no = tracker.sales_order_no
                AND order_map.order_date = tracker.order_date
                AND order_map.order_time = tracker.order_time
                AND order_map.customer_key = lower(trim(tracker.customer))
               JOIN workbook_import.customer_id_map AS customer_map
                 ON customer_map.customer_key = lower(trim(tracker.customer))
               ON CONFLICT (order_id) DO UPDATE SET
                   customer_id = EXCLUDED.customer_id,
                   order_date = EXCLUDED.order_date,
                   status = EXCLUDED.status,
                   total_amount = EXCLUDED.total_amount"""
        )
        connection.execute(
            """INSERT INTO public.order_items
                   (order_item_id, order_id, product_id, quantity, unit_price)
               SELECT item_map.order_item_id, order_map.order_id,
                      product_map.product_id, item.quantity, item.unit_price
               FROM workbook_import.items_sold_tracker AS item
               JOIN workbook_import.sales_order_tracker AS tracker
                 ON item.sales_order_no IS NOT DISTINCT FROM tracker.sales_order_no
                AND item.order_date IS NOT DISTINCT FROM tracker.order_date
                AND item.order_time IS NOT DISTINCT FROM tracker.order_time
                AND item.customer IS NOT DISTINCT FROM tracker.customer
               JOIN workbook_import.order_id_map AS order_map
                 ON order_map.sales_order_no = tracker.sales_order_no
                AND order_map.order_date = tracker.order_date
                AND order_map.order_time = tracker.order_time
                AND order_map.customer_key = lower(trim(tracker.customer))
               JOIN workbook_import.order_item_id_map AS item_map
                 ON item_map.source_file_name = item.source_file_name
                AND item_map.source_row_number = item.source_row_number
               JOIN workbook_import.product_id_map AS product_map
                 ON product_map.product_key = lower(trim(item.product))
               ON CONFLICT (order_item_id) DO UPDATE SET
                   order_id = EXCLUDED.order_id,
                   product_id = EXCLUDED.product_id,
                   quantity = EXCLUDED.quantity,
                   unit_price = EXCLUDED.unit_price"""
        )
        connection.execute(
            """INSERT INTO workbook_import.pipeline_quarantine
                   (source_table, source_file_sha256, source_file_name, source_row_number, reason_code)
               SELECT 'items_sold_tracker', item.source_file_sha256,
                      item.source_file_name, item.source_row_number,
                      CASE
                        WHEN order_map.order_id IS NULL AND product_map.product_id IS NULL
                          THEN 'unmatched_order_and_product'
                        WHEN order_map.order_id IS NULL THEN 'unmatched_order'
                        ELSE 'unmatched_product'
                      END
               FROM workbook_import.items_sold_tracker AS item
               LEFT JOIN workbook_import.order_id_map AS order_map
                 ON order_map.sales_order_no = item.sales_order_no
                AND order_map.order_date = item.order_date
                AND order_map.order_time = item.order_time
                AND order_map.customer_key = lower(trim(item.customer))
               LEFT JOIN workbook_import.product_id_map AS product_map
                 ON product_map.product_key = lower(trim(item.product))
               WHERE order_map.order_id IS NULL OR product_map.product_id IS NULL
               ON CONFLICT (source_table, source_file_sha256, source_row_number, reason_code)
               DO UPDATE SET last_seen_at = CURRENT_TIMESTAMP"""
        )
        order_count = connection.execute(
            "SELECT COUNT(*) FROM workbook_import.order_id_map"
        ).fetchone()[0]
        item_count = connection.execute(
            """SELECT COUNT(*) FROM public.order_items AS oi
               JOIN workbook_import.order_item_id_map AS item_map USING (order_item_id)"""
        ).fetchone()[0]
        quarantine_count = connection.execute(
            """SELECT COUNT(*) FROM workbook_import.pipeline_quarantine
               WHERE source_table = 'items_sold_tracker'"""
        ).fetchone()[0]

    return WorkbookOrderImportResult(
        orders=order_count,
        order_items=item_count,
        quarantined_order_items=quarantine_count,
    )


def main() -> int:
    try:
        result = import_workbook_orders_and_items()
    except (DatabaseConfigurationError, DatabaseConnectionError, WorkbookMappingError) as exc:
        print(f"Workbook order mapping failed: {exc}", file=sys.stderr)
        return 1
    except psycopg.Error:
        print("Workbook order mapping failed due to a database error", file=sys.stderr)
        return 1
    print(
        "Mapped canonical records: "
        f"orders={result.orders}, order_items={result.order_items}, "
        f"quarantined_item_rows={result.quarantined_order_items}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
